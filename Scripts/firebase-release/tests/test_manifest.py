import unittest

from firebase_release.manifest import ManifestSettings, render_manifest
from firebase_release.release_plan import (
    UMBRELLA_TARGET,
    ExternalBinary,
    PlannedProduct,
    PlannedSourceTarget,
    ReleasePlan,
)


class FakeArtifacts:
    def binary_target(self, name: str) -> str:
        return f'.binaryTarget(name: "{name}", path: "fake/{name}")'


SETTINGS = ManifestSettings(
    package_name="GooglePackages",
    firebase_version="13.2.0",
    ios_version="15",
    test_targets={"GooglePackagesTests": "GooglePackages"},
)

GTM = ExternalBinary(name="GoogleTagManager", url="https://example.com/gtm.zip", checksum="c0ffee")

FIREBASE_PLAN = ReleasePlan(
    products=(
        PlannedProduct(name="FirebaseAuth", targets=(UMBRELLA_TARGET, "FirebaseAuth", "FirebaseCore")),
        PlannedProduct(name="GoogleTagManager", targets=(UMBRELLA_TARGET, "FirebaseCore", "GoogleTagManager")),
    ),
    source_targets=(PlannedSourceTarget(name="GooglePackages", dependencies=(UMBRELLA_TARGET, "FirebaseAuth")),),
    binaries=("FirebaseAuth", "FirebaseCore"),
    external_binaries=(GTM,),
)

SIGN_IN_ONLY_PLAN = ReleasePlan(
    products=(PlannedProduct(name="GoogleSignIn", targets=("GoogleSignIn",)),),
    source_targets=(),
    binaries=("GoogleSignIn",),
    external_binaries=(),
)


class ManifestTests(unittest.TestCase):
    def setUp(self):
        self.manifest = render_manifest(FIREBASE_PLAN, FakeArtifacts(), SETTINGS)

    def test_says_it_is_generated_and_from_which_firebase_version(self):
        self.assertIn("Generated by Scripts/firebase-release", self.manifest)
        self.assertIn("Firebase 13.2.0", self.manifest)

    def test_declares_package_name_and_platform(self):
        self.assertIn('name: "GooglePackages"', self.manifest)
        self.assertIn("platforms: [.iOS(.v15)]", self.manifest)

    def test_every_planned_product_is_a_library_over_its_targets(self):
        self.assertIn(
            '.library(name: "FirebaseAuth", targets: ["Firebase", "FirebaseAuth", "FirebaseCore"])', self.manifest
        )
        self.assertIn('.library(name: "GoogleTagManager"', self.manifest)

    def test_source_target_and_its_test_target_are_declared(self):
        self.assertIn('.target(name: "GooglePackages", dependencies: ["Firebase", "FirebaseAuth"])', self.manifest)
        self.assertIn('.testTarget(name: "GooglePackagesTests", dependencies: ["GooglePackages"])', self.manifest)

    def test_binaries_come_from_the_artifact_source(self):
        self.assertIn('.binaryTarget(name: "FirebaseAuth", path: "fake/FirebaseAuth")', self.manifest)
        self.assertIn('.binaryTarget(name: "FirebaseCore", path: "fake/FirebaseCore")', self.manifest)

    def test_external_binaries_are_pinned_by_url_and_checksum(self):
        self.assertIn(
            '.binaryTarget(name: "GoogleTagManager", url: "https://example.com/gtm.zip", checksum: "c0ffee")',
            self.manifest,
        )

    def test_umbrella_target_exposes_firebase_header_and_links_system_libraries(self):
        self.assertIn('name: "Firebase"', self.manifest)
        self.assertIn('publicHeadersPath: "include"', self.manifest)
        self.assertIn('.linkedLibrary("c++")', self.manifest)
        self.assertIn('.linkedLibrary("sqlite3")', self.manifest)

    def test_umbrella_target_is_left_out_when_no_firebase_sdk_is_planned(self):
        manifest = render_manifest(SIGN_IN_ONLY_PLAN, FakeArtifacts(), SETTINGS)
        self.assertNotIn('name: "Firebase"', manifest)

    def test_has_no_package_dependencies(self):
        self.assertNotIn(".package(", self.manifest)

    def test_rendering_is_deterministic(self):
        self.assertEqual(self.manifest, render_manifest(FIREBASE_PLAN, FakeArtifacts(), SETTINGS))


if __name__ == "__main__":
    unittest.main()
