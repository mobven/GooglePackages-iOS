"""Renders Package.swift for a ReleasePlan. Where binaries live is delegated to an ArtifactSource."""
from dataclasses import dataclass, field
from typing import Dict, Iterable

try:
    from typing import Protocol
except ImportError:  # pragma: no cover - Python < 3.8
    Protocol = object

from .release_plan import UMBRELLA_TARGET, ReleasePlan

TOOLS_VERSION = "6.0"
UMBRELLA_PATH = "Sources/Firebase"
# Firebase's static xcframeworks need these at link time (see the zip's README.md and module maps).
UMBRELLA_LINKER_SETTINGS = (
    '.linkedLibrary("c++")',
    '.linkedLibrary("sqlite3")',
    '.linkedLibrary("z")',
    '.linkedFramework("AdSupport")',
    '.linkedFramework("CoreData")',
    '.linkedFramework("CoreTelephony")',
    '.linkedFramework("JavaScriptCore")',
    '.linkedFramework("Security")',
    '.linkedFramework("StoreKit")',
    '.linkedFramework("SystemConfiguration")',
    '.linkedFramework("UIKit")',
)


class ArtifactSource(Protocol):
    def binary_target(self, name: str) -> str:
        """The `.binaryTarget(...)` declaration for one xcframework."""


@dataclass(frozen=True)
class ManifestSettings:
    package_name: str
    firebase_version: str
    ios_version: str
    test_targets: Dict[str, str] = field(default_factory=dict)


def _names(names: Iterable[str]) -> str:
    return "[" + ", ".join(f'"{name}"' for name in names) + "]"


def _umbrella_target() -> str:
    linker_settings = "".join(f"\n                {setting}," for setting in UMBRELLA_LINKER_SETTINGS)
    return (
        ".target(\n"
        f'            name: "{UMBRELLA_TARGET}",\n'
        f'            path: "{UMBRELLA_PATH}",\n'
        '            publicHeadersPath: "include",\n'
        f"            linkerSettings: [{linker_settings}\n"
        "            ]\n"
        "        )"
    )


def render_manifest(plan: ReleasePlan, artifacts: ArtifactSource, settings: ManifestSettings) -> str:
    products = [f".library(name: \"{product.name}\", targets: {_names(product.targets)})" for product in plan.products]
    targets = [f".target(name: \"{source.name}\", dependencies: {_names(source.dependencies)})"
               for source in plan.source_targets]
    targets += [f".testTarget(name: \"{test}\", dependencies: {_names([subject])})"
                for test, subject in settings.test_targets.items()]
    if plan.needs_umbrella:
        targets.append(_umbrella_target())
    targets += [artifacts.binary_target(name) for name in plan.binaries]
    targets += [f'.binaryTarget(name: "{binary.name}", url: "{binary.url}", checksum: "{binary.checksum}")'
                for binary in plan.external_binaries]

    def block(items):
        return "".join(f"\n        {item}," for item in items)

    return (
        f"// swift-tools-version: {TOOLS_VERSION}\n"
        "// Generated by Scripts/firebase-release/release.py from the official\n"
        f"// Firebase {settings.firebase_version} XCFramework distribution. Do not edit by hand: rerun the script.\n"
        "\n"
        "import PackageDescription\n"
        "\n"
        "let package = Package(\n"
        f'    name: "{settings.package_name}",\n'
        f"    platforms: [.iOS(.v{settings.ios_version})],\n"
        f"    products: [{block(products)}\n"
        "    ],\n"
        f"    targets: [{block(targets)}\n"
        "    ]\n"
        ")\n"
    )
